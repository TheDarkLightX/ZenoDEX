"""WholeEconomyDisasterCoverageV1 functional core (public facade).

The core is values-only: no filesystem, subprocess, clock, environment, or
network access and no mutable module state.  It is split into cohesive
modules with explicit typed boundaries; this facade re-exports the public
surface used by the fixed-registry shell, the independent verifier, and the
tests.

    primitives  strict decoding, exact accessors, canonical hashing
    vocabulary  closed enumerations, limits, pinned source universe
    sources     source pins, owned reads, exact binding
    registry    closed registry model and parser
    inventory   targets, source universes, grid, obligation keys and rows
    subject     exact subject and execution premise
    evidence    observations, results, evidence lattice, result verification
    packet      denominator, flags, packet core, receipt root, verification

Claim ceiling: research-only denominator and evidence-association integrity.
``whole_economy_claim_allowed`` is constant ``False`` in V1.
"""

