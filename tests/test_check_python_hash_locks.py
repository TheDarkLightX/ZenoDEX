def test_missing_supported_root_lock_install_command_is_rejected(tmp_path: Path) -> None:
    for name in (
        "requirements-core.lock.txt",
        "requirements-agents.lock.txt",
        "requirements-dev.lock.txt",
    ):
        lock = tmp_path / name
        lock.write_text(
            "\n".join(
                (
                    "#",
                    "# This file is autogenerated by pip-compile",
                    "# by the following command:",
                    "#",
                    f"#    pip-compile --generate-hashes --output-file={name} {name.removesuffix('.lock.txt')}.txt",
                    "#",
                    "example==1.0 \\",
                    "    --hash=sha256:" + "a" * 64,
                )
            ),
            encoding="utf-8",
        )

    report = check_python_hash_locks.check_python_hash_locks(tmp_path)

    assert not report["ok"]
    assert report["root_dependency_commands"] == 0
    assert report["findings"] == [
        {
            "path": "install-surfaces",
            "line": 0,
            "code": "missing_hashed_root_install_command",
            "message": "supported install surfaces must include at least one root lockfile install command",
        }
    ]
