#[cfg(test)]
mod tests {
    use super::*;

    const GENESIS: [u16; SURFACE_COUNT] = [500, 100, 6000, 6000, 0, 2000, 2000, 11000, 15000];
    const PIN: [u8; 32] = [0xab; 32];

    fn chartered() -> EpochState {
        let s = genesis_state(GENESIS, 0);
        let (s, r) = renew_charter(&s, 0, 4096, PIN).unwrap();
        assert_eq!(r.code, Code::OkCharterRenewed);
        s
    }

    fn one(surface: Surface, d: i32) -> ([i32; SURFACE_COUNT], [bool; SURFACE_COUNT]) {
        let mut deltas = [0_i32; SURFACE_COUNT];
        let mut touched = [false; SURFACE_COUNT];
        deltas[surface as usize] = d;
        touched[surface as usize] = true;
        (deltas, touched)
    }

    #[test]
    fn genesis_is_fail_closed() {
        let s = genesis_state(GENESIS, 0);
        let (d, t) = one(Surface::FeeBps, 10);
        let (s2, r) = propose_revision(&s, &d, &t, 0).unwrap();
        assert_eq!(r.code, Code::RejCharterInvalid);
        assert_eq!(s2, s);
        assert_eq!(r.digest_before, r.digest_after);
    }

    #[test]
    fn walk_halts_at_drift_budget() {
        let mut s = chartered();
        let mut now: u16 = 0;
        let mut codes = vec![];
        for _ in 0..4 {
            let (d, t) = one(Surface::FeeBps, 50);
            let (s1, rp) = propose_revision(&s, &d, &t, now).unwrap();
            assert_eq!(rp.code, Code::OkProposed);
            now += GOV_COOLDOWN_EPOCHS;
            let (s2, ra) = apply_pending(&s1, now);
            codes.push(ra.code);
            s = s2;
        }
        assert_eq!(
            codes,
            vec![Code::OkApplied, Code::OkApplied, Code::OkApplied, Code::RejDriftBudget]
        );
        assert_eq!(s.params[Surface::FeeBps as usize], 650);
    }

    #[test]
    fn timelock_keeps_pending_cooldown_clears_it() {
        let s = chartered();
        let (d, t) = one(Surface::FeeBps, 50);
        let (s1, _) = propose_revision(&s, &d, &t, 0).unwrap();
        let (s2, r) = apply_pending(&s1, MIN_DELAY - 1);
        assert_eq!(r.code, Code::RejTimelock);
        assert!(s2.pending.is_some()); // KEPT
        let (s3, r2) = apply_pending(&s2, GOV_COOLDOWN_EPOCHS);
        assert_eq!(r2.code, Code::OkApplied);
        let (d2, t2) = one(Surface::FeeBps, 10);
        let (s4, _) = propose_revision(&s3, &d2, &t2, GOV_COOLDOWN_EPOCHS).unwrap();
        let (s5, r3) = apply_pending(&s4, GOV_COOLDOWN_EPOCHS + MIN_DELAY);
        assert_eq!(r3.code, Code::RejCooldown);
        assert_eq!(r3.surface, Some("fee_bps"));
        assert!(s5.pending.is_none()); // CLEARED
    }

    #[test]
    fn coordinated_walk_hits_epoch_budget() {
        let s = chartered();
        let deltas: [i32; SURFACE_COUNT] = [50, 25, 500, -500, 500, -500, 500, 1000, 1000];
        let touched = [true; SURFACE_COUNT];
        let (s1, rp) = propose_revision(&s, &deltas, &touched, 0).unwrap();
        assert_eq!(rp.code, Code::OkProposed);
        let (s2, r) = apply_pending(&s1, GOV_COOLDOWN_EPOCHS);
        assert_eq!(r.code, Code::RejEpochBudget);
        assert_eq!(s2.params, GENESIS); // all-or-nothing
    }

    #[test]
    fn veto_and_freeze_paths() {
        let s = chartered();
        let (d, t) = one(Surface::FeeBps, 50);
        let (s1, _) = propose_revision(&s, &d, &t, 0).unwrap();
        let (s2, _) = set_frozen(&s1, true, 1);
        let (s3, rv) = veto_pending(&s2, 2);
        assert_eq!(rv.code, Code::OkVetoed); // veto works while frozen
        let (_, ra) = apply_pending(&s3, GOV_COOLDOWN_EPOCHS);
        assert_eq!(ra.code, Code::RejNoPending);
    }

    #[test]
    fn digest_matches_lib_btreemap_encoder() {
        // the array encoder and the BTreeMap encoder must agree byte-for-byte
        let arr_digest = params_digest_arr(&GENESIS);
        let map: std::collections::BTreeMap<String, u16> = SURFACES
            .iter()
            .map(|s| (s.name().to_string(), GENESIS[*s as usize]))
            .collect();
        assert_eq!(arr_digest, crate::params_digest(&map).expect("exact surface set"));
    }
}

// ---------------------------------------------------------------------------
// Kani harnesses over the FULL symbolic state space (digest-free core only).
// Run: cargo kani -p zenodex-governance-gate
// ---------------------------------------------------------------------------
#[cfg(kani)]
mod verification {
    use super::*;

    fn any_state() -> EpochState {
        let mut params = [0_u16; SURFACE_COUNT];
        let mut traj = [SurfaceTraj {
            last_revision_epoch: 0,
            window_start_epoch: 0,
            drift_used: 0,
        }; SURFACE_COUNT];
        let mut i = 0;
        while i < SURFACE_COUNT {
            params[i] = kani::any();
            traj[i] = SurfaceTraj {
                last_revision_epoch: kani::any(),
                window_start_epoch: kani::any(),
                drift_used: kani::any(),
            };
            i += 1;
        }
        let charter = if kani::any() {
            Some(Charter {
                granted_epoch: kani::any(),
                ttl: kani::any(),
                revoked: kani::any(),
                policy_pin: [0_u8; 32], // pin is audit metadata; validity ignores it
            })
        } else {
            None
        };
        let pending = if kani::any() {
            let mut deltas = [0_i32; SURFACE_COUNT];
            let mut touched = [false; SURFACE_COUNT];
            let mut j = 0;
            while j < SURFACE_COUNT {
                let d: i32 = kani::any();
                kani::assume((-(0xFFFF_i32)..=0xFFFF_i32).contains(&d));
                deltas[j] = d;
                touched[j] = kani::any();
                j += 1;
            }
            Some(PendingRevision { deltas, touched, proposed_epoch: kani::any() })
        } else {
            None
        };
        EpochState { params, traj, charter, frozen: kani::any(), pending }
    }

    /// THE machine-level CBC property, over the whole bounded domain: any
    /// apply outcome other than OkApplied leaves params, trajectories,
    /// charter, and the freeze flag untouched (pending may clear by design).
    #[kani::proof]
    fn apply_reject_is_noop() {
        let s = any_state();
        let now: u16 = kani::any();
        let (post, code, _at) = apply_pending_core(&s, now);
        if code != Code::OkApplied {
            assert!(post.params == s.params);
            assert!(post.traj == s.traj);
            assert!(post.charter == s.charter);
            assert!(post.frozen == s.frozen);
        }
    }

    /// Pending lifecycle on apply: kept ONLY on the timelock reject; cleared
    /// on every other reject (when one existed); always cleared on apply.
    #[kani::proof]
    fn apply_pending_kept_vs_cleared() {
        let s = any_state();
        let now: u16 = kani::any();
        let (post, code, _at) = apply_pending_core(&s, now);
        match code {
            Code::RejNoPending => assert!(post.pending.is_none() && s.pending.is_none()),
            Code::RejTimelock => assert!(post.pending == s.pending),
            _ => assert!(post.pending.is_none()),
        }
    }

    /// Accept ⇒ authority invariants, for every touched surface: the timelock
    /// and per-surface cooldown held, the drift charge fits the window budget,
    /// and the bookkeeping is exactly the documented update.
    #[kani::proof]
    fn apply_accept_bookkeeping_and_bounds() {
        let s = any_state();
        let now: u16 = kani::any();
        let (post, code, _at) = apply_pending_core(&s, now);
        if code == Code::OkApplied {
            let p = s.pending.unwrap();
            assert!(post.pending.is_none());
            // timelock held (subtraction-guard form)
            assert!(now >= p.proposed_epoch && now - p.proposed_epoch >= MIN_DELAY);
            let mut i = 0;
            while i < SURFACE_COUNT {
                if p.touched[i] {
                    // cooldown held against the PRE-state trajectory
                    let last = s.traj[i].last_revision_epoch;
                    assert!(now >= last && now - last >= GOV_COOLDOWN_EPOCHS);
                    // drift charge within the window budget
                    assert!(post.traj[i].drift_used <= SURFACES[i].drift_budget());
                    assert!(post.traj[i].last_revision_epoch == now);
                    // the applied delta is exactly the pending delta
                    let next = i64::from(s.params[i]) + i64::from(p.deltas[i]);
                    assert!(i64::from(post.params[i]) == next);
                } else {
                    assert!(post.params[i] == s.params[i]);
                    assert!(post.traj[i] == s.traj[i]);
                }
                i += 1;
            }
        }
    }

    /// Accept ⇒ surface-band invariants: scalars inside their caps/steps, the
    /// router shares summing exactly to SPLIT_SUM when touched, the collateral
    /// pair ordered inside floor/ceiling.
    #[kani::proof]
    fn apply_accept_band_invariants() {
        let s = any_state();
        let now: u16 = kani::any();
        let (post, code, _at) = apply_pending_core(&s, now);
        if code == Code::OkApplied {
            let p = s.pending.unwrap();
            if p.touched[Surface::FeeBps as usize] {
                assert!(post.params[Surface::FeeBps as usize] <= crate::FEE_MAX_BPS);
            }
            if p.touched[Surface::FundingCapBps as usize] {
                assert!(post.params[Surface::FundingCapBps as usize] <= crate::FUNDING_CAP_MAX_BPS);
            }
            if p.touched[Surface::RedeemStakerBps as usize] {
                assert!(post.params[Surface::RedeemStakerBps as usize] <= crate::WHALE_STAKER_BPS_MAX);
            }
            let router_touched = p.touched[Surface::BuyburnBps as usize]
                || p.touched[Surface::StakersBps as usize]
                || p.touched[Surface::ReserveBps as usize]
                || p.touched[Surface::HostsBps as usize];
            if router_touched {
                let sum: u32 = u32::from(post.params[Surface::BuyburnBps as usize])
                    + u32::from(post.params[Surface::StakersBps as usize])
                    + u32::from(post.params[Surface::ReserveBps as usize])
                    + u32::from(post.params[Surface::HostsBps as usize]);
                assert!(sum == u32::from(crate::SPLIT_SUM));
            }
            let coll_touched =
                p.touched[Surface::McrBps as usize] || p.touched[Surface::CcrBps as usize];
            if coll_touched {
                let mcr = post.params[Surface::McrBps as usize];
                let ccr = post.params[Surface::CcrBps as usize];
                assert!(mcr >= crate::RATIO_MIN_BPS);
                assert!(ccr <= crate::RATIO_MAX_BPS);
                assert!(mcr <= ccr);
            }
        }
    }

    /// Accept ⇒ the standing approval really held at `now` (dead-man teeth):
    /// an apply can never fire revoked, expired, never-chartered, or frozen.
    #[kani::proof]
    fn apply_accept_requires_live_charter_and_thaw() {
        let s = any_state();
        let now: u16 = kani::any();
        let (_post, code, _at) = apply_pending_core(&s, now);
        if code == Code::OkApplied {
            assert!(!s.frozen);
            let c = s.charter.unwrap();
            assert!(!c.revoked);
            assert!(c.ttl <= CHARTER_TTL_MAX);
            assert!(now >= c.granted_epoch && now - c.granted_epoch < c.ttl);
        }
    }

    /// Precedence dominance pins: no-pending answers before any authority
    /// question; freeze answers before charter/timelock.
    #[kani::proof]
    fn apply_precedence_dominance() {
        let s = any_state();
        let now: u16 = kani::any();
        let (_post, code, _at) = apply_pending_core(&s, now);
        if s.pending.is_none() {
            assert!(code == Code::RejNoPending);
        } else if s.frozen {
            assert!(code == Code::RejFrozen);
        }
    }

    /// Propose: reject is a FULL no-op; accept changes ONLY pending, and the
    /// recorded action zeroes untouched deltas (no smuggled payload).
    #[kani::proof]
    fn propose_isolation() {
        let s = any_state();
        let now: u16 = kani::any();
        let mut deltas = [0_i32; SURFACE_COUNT];
        let mut touched = [false; SURFACE_COUNT];
        let mut i = 0;
        while i < SURFACE_COUNT {
            let d: i32 = kani::any();
            kani::assume((-(0xFFFF_i32)..=0xFFFF_i32).contains(&d));
            deltas[i] = d;
            touched[i] = kani::any();
            i += 1;
        }
        let (post, code) = match propose_revision_core(&s, &deltas, &touched, now) {
            Ok(v) => v,
            Err(_) => return, // magnitude guard: unreachable under the assume
        };
        if code == Code::OkProposed {
            assert!(post.params == s.params && post.traj == s.traj);
            assert!(post.charter == s.charter && post.frozen == s.frozen);
            let p = post.pending.unwrap();
            assert!(p.proposed_epoch == now);
            let mut j = 0;
            while j < SURFACE_COUNT {
                if p.touched[j] {
                    assert!(p.deltas[j] == deltas[j]);
                } else {
                    assert!(p.deltas[j] == 0);
                }
                j += 1;
            }
        } else {
            assert!(post == s);
        }
    }

    /// Veto / revoke / freeze field isolation: each transition touches exactly
    /// its own field, never the params or trajectories.
    #[kani::proof]
    fn stop_authorities_field_isolation() {
        let s = any_state();
        let now: u16 = kani::any();
        let (v, vcode) = veto_pending_core(&s, now);
        assert!(v.params == s.params && v.traj == s.traj && v.charter == s.charter);
        if vcode == Code::RejNoPending {
            assert!(v == s);
        } else {
            assert!(v.pending.is_none());
        }
        let (r, rcode) = revoke_charter_core(&s, now);
        assert!(r.params == s.params && r.traj == s.traj && r.pending == s.pending);
        if rcode == Code::OkCharterRevoked {
            assert!(r.charter.unwrap().revoked);
        } else {
            assert!(r == s);
        }
        let flag: bool = kani::any();
        let (f, _) = set_frozen_core(&s, flag, now);
        assert!(f.params == s.params && f.traj == s.traj);
        assert!(f.charter == s.charter && f.pending == s.pending);
        assert!(f.frozen == flag);
    }
}
