//! Epoch-machine transition core (Rust mirror of `gov_epoch.py`).
//!
//! The verdict kernel (`lib.rs`) answers "is this revision admissible?"; this
//! module ports the MACHINE around it: propose → timelock/veto window →
//! all-or-nothing apply through every tier in the FIXED precedence, charter
//! renew/revoke, the freeze interlock, and the trajectory bookkeeping
//! (cooldowns, window-rolled drift budgets, the aggregate epoch budget).
//!
//! DESIGN: invalid states are unrepresentable. Surfaces are an enum (no
//! unknown-surface paths), the state is fixed-size arrays over `u16` (no maps,
//! no heap in the core), flags are real bools. The entire hostile-object tier
//! of `gov_epoch.py` — exact-type guards, use-time re-validation, snapshot
//! discipline, canonical-tuple checks — exists because Python cannot make
//! those states unrepresentable; here the type system carries it, and what
//! remains to verify is the TRANSITION LOGIC itself.
//!
//! CORE / RECEIPT SPLIT: `*_core` functions are pure, allocation-free, and
//! return `(State, Code, Option<Surface>)` — these are the Kani targets
//! (sha256 is excluded from the symbolic path by construction). The public
//! wrappers add the canonical params digests and produce `EpochReceipt`,
//! mirroring `gov_epoch.GovReceipt` field-for-field; the cross-language
//! scenario fixture (generated by replaying `gov_epoch.py`) binds the two
//! implementations transition-by-transition.
//!
//! SEMANTIC PARITY NOTES (each mirrors a documented gov_epoch.py rule):
//! - apply precedence: no_pending → frozen → charter → timelock(pending KEPT)
//!   → cooldown (touched surfaces in declaration order) → pointwise gates
//!   (scalars fee/funding/whale, then router AS A UNIT, then collateral AS A
//!   UNIT) → window-rolled drift budgets (touched order) → aggregate epoch
//!   budget → apply. Pending is KEPT only on the timelock reject.
//! - the lane's `approved` IS charter validity (checked before the gates run).
//! - a window only rolls when `now − window_start ≥ DRIFT_WINDOW_EPOCHS` with
//!   the wrap-guard; a "future" window_start never rolls (fail-closed), and
//!   roll state commits ONLY on a full apply.
//! - Python's TypeError/ValueError paths for hostile/malformed objects are
//!   unrepresentable here; the two value-domain errors that remain
//!   (charter ttl, delta magnitude) are `EpochError` — `Err` corresponds to
//!   "gov_epoch raises", reject receipts to "well-formed but inadmissible".

use crate::{
    charter_ok, collateral_ratio_revision_ok, cooldown_ok, drift_budget_ok, epoch_budget_ok,
    fee_revision_ok, funding_rate_revision_ok, router_revision_ok, whale_defense_revision_ok,
    CHARTER_TTL_MAX, DRIFT_WINDOW_EPOCHS, EPOCH_MOVEMENT_BUDGET, FEE_STEP_BPS, FUNDING_STEP_BPS,
    GOV_COOLDOWN_EPOCHS, MIN_DELAY, RATIO_STEP_BPS, SPLIT_STEP_BPS, WHALE_STEP_BPS,
};
use sha2::{Digest, Sha256};

pub const SURFACE_COUNT: usize = 9;

/// The nine governed surfaces, in `gov_epoch.ALL_SURFACES` DECLARATION order
/// (scalars, router shares, collateral pair) — this is the order the cooldown
/// and drift loops consult, so first-failing-surface receipts match Python.
/// (The canonical digest uses SORTED name order; see `params_digest_arr`.)
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Surface {
    FeeBps = 0,
    FundingCapBps = 1,
    RedeemStakerBps = 2,
    BuyburnBps = 3,
    StakersBps = 4,
    ReserveBps = 5,
    HostsBps = 6,
    McrBps = 7,
    CcrBps = 8,
}

pub const SURFACES: [Surface; SURFACE_COUNT] = [
    Surface::FeeBps,
    Surface::FundingCapBps,
    Surface::RedeemStakerBps,
    Surface::BuyburnBps,
    Surface::StakersBps,
    Surface::ReserveBps,
    Surface::HostsBps,
    Surface::McrBps,
    Surface::CcrBps,
];

impl Surface {
    pub fn name(self) -> &'static str {
        match self {
            Surface::FeeBps => "fee_bps",
            Surface::FundingCapBps => "funding_cap_bps",
            Surface::RedeemStakerBps => "redeem_staker_bps",
            Surface::BuyburnBps => "buyburn_bps",
            Surface::StakersBps => "stakers_bps",
            Surface::ReserveBps => "reserve_bps",
            Surface::HostsBps => "hosts_bps",
            Surface::McrBps => "mcr_bps",
            Surface::CcrBps => "ccr_bps",
        }
    }

    pub fn from_name(name: &str) -> Option<Surface> {
        SURFACES.iter().copied().find(|s| s.name() == name)
    }

    /// Per-surface window drift budget (mirrors gov_gate.DRIFT_BUDGET_BPS:
    /// 3 pointwise steps per window).
    pub fn drift_budget(self) -> u16 {
        match self {
            Surface::FeeBps => 3 * FEE_STEP_BPS,
            Surface::FundingCapBps => 3 * FUNDING_STEP_BPS,
            Surface::RedeemStakerBps => 3 * WHALE_STEP_BPS,
            Surface::BuyburnBps | Surface::StakersBps | Surface::ReserveBps
            | Surface::HostsBps => 3 * SPLIT_STEP_BPS,
            Surface::McrBps | Surface::CcrBps => 3 * RATIO_STEP_BPS,
        }
    }
}

const SCALARS: [Surface; 3] = [Surface::FeeBps, Surface::FundingCapBps, Surface::RedeemStakerBps];
const ROUTER: [Surface; 4] =
    [Surface::BuyburnBps, Surface::StakersBps, Surface::ReserveBps, Surface::HostsBps];
const COLLATERAL: [Surface; 2] = [Surface::McrBps, Surface::CcrBps];

/// Per-surface trajectory bookkeeping (mirrors gov_epoch.SurfaceTraj).
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct SurfaceTraj {
    pub last_revision_epoch: u16,
    pub window_start_epoch: u16,
    pub drift_used: u16,
}

/// Standing approval (mirrors gov_epoch.Charter; the policy pin is boundary
/// metadata carried for receipts/audit — charter VALIDITY ignores it).
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct Charter {
    pub granted_epoch: u16,
    pub ttl: u16,
    pub revoked: bool,
    pub policy_pin: [u8; 32],
}

/// A queued multi-surface action maturing in the timelock/veto window.
/// `touched[i]` gates whether `deltas[i]` is part of the action.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct PendingRevision {
    pub deltas: [i32; SURFACE_COUNT],
    pub touched: [bool; SURFACE_COUNT],
    pub proposed_epoch: u16,
}

impl PendingRevision {
    pub fn is_empty(&self) -> bool {
        !self.touched.iter().any(|&t| t)
    }
}

/// The governed envelope's committed state (mirrors gov_epoch.GovEpochState).
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct EpochState {
    pub params: [u16; SURFACE_COUNT],
    pub traj: [SurfaceTraj; SURFACE_COUNT],
    pub charter: Option<Charter>,
    pub frozen: bool,
    pub pending: Option<PendingRevision>,
}

