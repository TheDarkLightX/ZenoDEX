pub fn propose_revision_core(
    state: &EpochState,
    deltas: &[i32; SURFACE_COUNT],
    touched: &[bool; SURFACE_COUNT],
    now_epoch: u16,
) -> Result<(EpochState, Code), EpochError> {
    for i in 0..SURFACE_COUNT {
        if touched[i] && !(-(0xFFFF_i32)..=0xFFFF_i32).contains(&deltas[i]) {
            return Err(EpochError::DeltaOutOfRange);
        }
    }
    if state.frozen {
        return Ok((*state, Code::RejFrozen));
    }
    if state.pending.is_some() {
        return Ok((*state, Code::RejPendingExists));
    }
    if !charter_valid(state, now_epoch) {
        return Ok((*state, Code::RejCharterInvalid));
    }
    if !touched.iter().any(|&t| t) {
        return Ok((*state, Code::RejEmptyAction));
    }
    let mut clean = [0_i32; SURFACE_COUNT];
    for i in 0..SURFACE_COUNT {
        if touched[i] {
            clean[i] = deltas[i];
        }
    }
    let mut new = *state;
    new.pending = Some(PendingRevision {
        deltas: clean,
        touched: *touched,
        proposed_epoch: now_epoch,
    });
    Ok((new, Code::OkProposed))
}

pub fn veto_pending_core(state: &EpochState, _now_epoch: u16) -> (EpochState, Code) {
    // never gated: stopping is always safe (works frozen and unchartered)
    match state.pending {
        None => (*state, Code::RejNoPending),
        Some(_) => {
            let mut new = *state;
            new.pending = None;
            (new, Code::OkVetoed)
        }
    }
}

/// The apply pipeline. Returns the post-state, the code, and the
/// first-failing surface/group label where applicable.
pub fn apply_pending_core(
    state: &EpochState,
    now_epoch: u16,
) -> (EpochState, Code, Option<RejectAt>) {
    let pending = match state.pending {
        None => return (*state, Code::RejNoPending, None),
        Some(p) => p,
    };
    let cleared = {
        let mut s = *state;
        s.pending = None;
        s
    };
    if state.frozen {
        return (cleared, Code::RejFrozen, None);
    }
    if !charter_valid(state, now_epoch) {
        return (cleared, Code::RejCharterInvalid, None);
    }
    // timelock: pending KEPT (not yet mature — wait and retry)
    if !cooldown_ok(pending.proposed_epoch, now_epoch, MIN_DELAY) {
        return (*state, Code::RejTimelock, None);
    }
    // per-surface cooldown, declaration order
    for (i, s) in SURFACES.iter().enumerate() {
        if pending.touched[i]
            && !cooldown_ok(state.traj[i].last_revision_epoch, now_epoch, GOV_COOLDOWN_EPOCHS)
        {
            return (cleared, Code::RejCooldown, Some(RejectAt::Surface(*s)));
        }
    }

    // candidate next values (i64 to carry out-of-band candidates to the gates,
    // which reject them exactly as Python's domain guards do)
    let mut next = [0_i64; SURFACE_COUNT];
    for i in 0..SURFACE_COUNT {
        // |params| <= 0xFFFF and |delta| <= 0xFFFF: saturation is unreachable,
        // written saturating to satisfy the checked-arithmetic lint exactly.
        next[i] = i64::from(state.params[i])
            .saturating_add(if pending.touched[i] { i64::from(pending.deltas[i]) } else { 0 });
    }
    let in_band = |v: i64| -> Option<u16> { u16::try_from(v).ok() };

    // pointwise gates, the multi-surface order: scalars -> router unit -> collateral unit.
    // approved=True IS charter validity (established above); timelock re-checked by the
    // gates with the same subtraction-guard (already known to pass).
    let scalar_gate = |s: Surface, curr: u16, nxt: u16| -> bool {
        match s {
            Surface::FeeBps => {
                fee_revision_ok(true, true, pending.proposed_epoch, now_epoch, curr, nxt)
            }
            Surface::FundingCapBps => {
                funding_rate_revision_ok(true, true, pending.proposed_epoch, now_epoch, curr, nxt)
            }
            Surface::RedeemStakerBps => {
                whale_defense_revision_ok(true, true, pending.proposed_epoch, now_epoch, curr, nxt)
            }
            _ => false,
        }
    };
    for s in SCALARS {
        let i = s as usize;
        if pending.touched[i] {
            let ok = match in_band(next[i]) {
                Some(nxt) => scalar_gate(s, state.params[i], nxt),
                None => false, // Python: gate domain guard rejects the raw int
            };
            if !ok {
                return (cleared, Code::RejSurfaceGate, Some(RejectAt::Surface(s)));
            }
        }
    }
    if ROUTER.iter().any(|&s| pending.touched[s as usize]) {
        let nx: Option<[u16; 4]> = (|| {
            Some([
                in_band(next[Surface::BuyburnBps as usize])?,
                in_band(next[Surface::StakersBps as usize])?,
                in_band(next[Surface::ReserveBps as usize])?,
                in_band(next[Surface::HostsBps as usize])?,
            ])
        })();
        let ok = match nx {
            Some([b, st, r, h]) => router_revision_ok(
                true, true, pending.proposed_epoch, now_epoch,
                b, st, r, h,
                state.params[Surface::BuyburnBps as usize],
                state.params[Surface::StakersBps as usize],
                state.params[Surface::ReserveBps as usize],
                state.params[Surface::HostsBps as usize],
            ),
            None => false,
        };
        if !ok {
            return (cleared, Code::RejSurfaceGate, Some(RejectAt::Router));
        }
    }
    if COLLATERAL.iter().any(|&s| pending.touched[s as usize]) {
        let mcr_i = Surface::McrBps as usize;
        let ccr_i = Surface::CcrBps as usize;
        let ok = match (in_band(next[mcr_i]), in_band(next[ccr_i])) {
            (Some(mn), Some(cn)) => collateral_ratio_revision_ok(
                true, true, pending.proposed_epoch, now_epoch,
                state.params[mcr_i], mn, state.params[ccr_i], cn,
            ),
            _ => false,
        };
        if !ok {
            return (cleared, Code::RejSurfaceGate, Some(RejectAt::Collateral));
        }
    }

    // window-rolled drift budgets (touched order); roll commits ONLY on apply
    let mut rolled: [SurfaceTraj; SURFACE_COUNT] = state.traj;
    for (i, s) in SURFACES.iter().enumerate() {
        if !pending.touched[i] {
            continue;
        }
        let t = state.traj[i];
        // wrap-guarded roll; a "future" window_start never rolls (fail-closed)
        let fresh = now_epoch
            .checked_sub(t.window_start_epoch)
            .is_some_and(|age| age >= DRIFT_WINDOW_EPOCHS);
        let used = if fresh { 0 } else { t.drift_used };
        let start = if fresh { now_epoch } else { t.window_start_epoch };
        // gates passed => next[i] is in the surface band, hence in u16
        let nxt = match in_band(next[i]) {
            Some(v) => v,
            None => return (cleared, Code::RejDriftBudget, Some(RejectAt::Surface(*s))),
        };
        if !drift_budget_ok(state.params[i], nxt, used, s.drift_budget()) {
            return (cleared, Code::RejDriftBudget, Some(RejectAt::Surface(*s)));
        }
        let mag = pending.deltas[i].unsigned_abs().min(0xFFFF) as u16;
        rolled[i] = SurfaceTraj {
            last_revision_epoch: now_epoch,
            window_start_epoch: start,
            // admitted => mag <= budget - used <= 0xFFFF: no overflow
            drift_used: used.saturating_add(mag),
        };
    }

    // aggregate epoch budget over the three gate groups
    let group_sum = |members: &[Surface]| -> u16 {
        let mut acc: u32 = 0;
        for &s in members {
            let i = s as usize;
            if pending.touched[i] {
                acc = acc.saturating_add(pending.deltas[i].unsigned_abs().min(0xFFFF));
            }
        }
        // each group has <= 4 members of <= 0xFFFF; Python passes exact sums —
        // values above u16 would be rejected by epoch_budget_ok's domain in
        // Python (in_domain fails) => mirror by saturating into the reject
        u16::try_from(acc).unwrap_or(u16::MAX)
    };
    let ok = epoch_budget_ok(
        group_sum(&SCALARS),
        group_sum(&ROUTER),
        group_sum(&COLLATERAL),
        EPOCH_MOVEMENT_BUDGET,
    );
    if !ok {
        return (cleared, Code::RejEpochBudget, None);
    }

    // all tiers passed: commit params + trajectories, clear pending
    let mut new = *state;
    for i in 0..SURFACE_COUNT {
        if pending.touched[i] {
            // gates admitted => in band
            new.params[i] = in_band(next[i]).unwrap_or(new.params[i]);
            new.traj[i] = rolled[i];
        }
    }
    new.pending = None;
    (new, Code::OkApplied, None)
}

pub fn renew_charter_core(
    state: &EpochState,
    now_epoch: u16,
    ttl: u16,
    policy_pin: [u8; 32],
) -> Result<(EpochState, Code), EpochError> {
    if ttl == 0 || ttl > CHARTER_TTL_MAX {
        return Err(EpochError::TtlOutOfRange);
    }
    let mut new = *state;
    new.charter = Some(Charter { granted_epoch: now_epoch, ttl, revoked: false, policy_pin });
    Ok((new, Code::OkCharterRenewed))
}

pub fn revoke_charter_core(state: &EpochState, _now_epoch: u16) -> (EpochState, Code) {
    // never gated: stopping is always safe; idempotent
    match state.charter {
        None => (*state, Code::RejNoCharter),
        Some(c) => {
            let mut new = *state;
            new.charter = Some(Charter { revoked: true, ..c });
            (new, Code::OkCharterRevoked)
        }
    }
}

pub fn set_frozen_core(state: &EpochState, flag: bool, _now_epoch: u16) -> (EpochState, Code) {
    let mut new = *state;
    new.frozen = flag;
    (new, Code::OkFrozenSet)
}

