/// Reject-surface label: Python reports a SURFACE name for scalar/cooldown/
/// drift rejects but the GROUP name ("router"/"collateral") for unit rejects.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum RejectAt {
    Surface(Surface),
    Router,
    Collateral,
}

impl RejectAt {
    pub fn label(self) -> &'static str {
        match self {
            RejectAt::Surface(s) => s.name(),
            RejectAt::Router => "router",
            RejectAt::Collateral => "collateral",
        }
    }
}

/// "gov_epoch raises" equivalents — the only two value-domain errors the
/// typed core can still express.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum EpochError {
    /// renew_charter ttl outside [1, CHARTER_TTL_MAX] (no perpetual charter).
    TtlOutOfRange,
    /// a delta magnitude outside the bv[16] band (|d| > 0xFFFF).
    DeltaOutOfRange,
}

/// Canonical genesis (mirrors gov_epoch.genesis_state): autonomy DISABLED
/// (no charter — fail-closed), trajectory clocks start at `epoch`.
pub fn genesis_state(params: [u16; SURFACE_COUNT], epoch: u16) -> EpochState {
    EpochState {
        params,
        traj: [SurfaceTraj {
            last_revision_epoch: epoch,
            window_start_epoch: epoch,
            drift_used: 0,
        }; SURFACE_COUNT],
        charter: None,
        frozen: false,
        pending: None,
    }
}

fn charter_valid(state: &EpochState, now_epoch: u16) -> bool {
    match state.charter {
        None => false,
        Some(c) => charter_ok(c.revoked, c.granted_epoch, now_epoch, c.ttl),
    }
}

