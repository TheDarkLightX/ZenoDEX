/// Canonical outcome of one transition (mirrors gov_epoch.GovReceipt).
#[derive(Clone, PartialEq, Eq, Debug)]
pub struct EpochReceipt {
    pub code: Code,
    pub epoch: u16,
    pub surface: Option<&'static str>,
    pub digest_before: String,
    pub digest_after: String,
    pub policy_pin: Option<[u8; 32]>,
}

/// Canonical digest of a params array — byte-identical to
/// `gov_epoch.params_digest` (sorted name order, `[["k",v],...]`, no spaces).
pub fn params_digest_arr(params: &[u16; SURFACE_COUNT]) -> String {
    // sorted name order over the fixed surface set
    let mut order: [usize; SURFACE_COUNT] = [0, 1, 2, 3, 4, 5, 6, 7, 8];
    order.sort_by_key(|&i| SURFACES[i].name());
    let mut canonical = String::from("[");
    let mut first = true;
    for &i in &order {
        if !first {
            canonical.push(',');
        }
        first = false;
        canonical.push_str("[\"");
        canonical.push_str(SURFACES[i].name());
        canonical.push_str("\",");
        canonical.push_str(crate::itoa_u16(params[i]).as_str());
        canonical.push(']');
    }
    canonical.push(']');
    let mut hasher = Sha256::new();
    hasher.update(canonical.as_bytes());
    hex::encode(hasher.finalize())
}

fn pin_of(state: &EpochState) -> Option<[u8; 32]> {
    state.charter.map(|c| c.policy_pin)
}

fn receipt(
    code: Code,
    epoch: u16,
    surface: Option<RejectAt>,
    before: &EpochState,
    after: &EpochState,
    pin: Option<[u8; 32]>,
) -> EpochReceipt {
    EpochReceipt {
        code,
        epoch,
        surface: surface.map(RejectAt::label),
        digest_before: params_digest_arr(&before.params),
        digest_after: params_digest_arr(&after.params),
        policy_pin: pin,
    }
}

pub fn propose_revision(
    state: &EpochState,
    deltas: &[i32; SURFACE_COUNT],
    touched: &[bool; SURFACE_COUNT],
    now_epoch: u16,
) -> Result<(EpochState, EpochReceipt), EpochError> {
    let pin = pin_of(state);
    let (new, code) = propose_revision_core(state, deltas, touched, now_epoch)?;
    let r = receipt(code, now_epoch, None, state, &new, pin);
    Ok((new, r))
}

pub fn veto_pending(state: &EpochState, now_epoch: u16) -> (EpochState, EpochReceipt) {
    let pin = pin_of(state);
    let (new, code) = veto_pending_core(state, now_epoch);
    let r = receipt(code, now_epoch, None, state, &new, pin);
    (new, r)
}

pub fn apply_pending(state: &EpochState, now_epoch: u16) -> (EpochState, EpochReceipt) {
    let pin = pin_of(state);
    let (new, code, at) = apply_pending_core(state, now_epoch);
    let r = receipt(code, now_epoch, at, state, &new, pin);
    (new, r)
}

pub fn renew_charter(
    state: &EpochState,
    now_epoch: u16,
    ttl: u16,
    policy_pin: [u8; 32],
) -> Result<(EpochState, EpochReceipt), EpochError> {
    let (new, code) = renew_charter_core(state, now_epoch, ttl, policy_pin)?;
    // mirrors gov_epoch: the renewal receipt carries the NEW pin
    let r = receipt(code, now_epoch, None, state, &new, Some(policy_pin));
    Ok((new, r))
}

pub fn revoke_charter(state: &EpochState, now_epoch: u16) -> (EpochState, EpochReceipt) {
    let pin = pin_of(state);
    let (new, code) = revoke_charter_core(state, now_epoch);
    // mirrors gov_epoch: no-charter reject carries pin=None; revocation carries the pin
    let r = receipt(code, now_epoch, None, state, &new, if state.charter.is_some() { pin } else { None });
    (new, r)
}

pub fn set_frozen(state: &EpochState, flag: bool, now_epoch: u16) -> (EpochState, EpochReceipt) {
    let pin = pin_of(state);
    let (new, code) = set_frozen_core(state, flag, now_epoch);
    let r = receipt(code, now_epoch, None, state, &new, pin);
    (new, r)
}

